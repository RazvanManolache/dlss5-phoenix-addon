"""Regenerate attributed model layout headers from maintained declarations.

The JSON preserves existing model knowledge; generation does not establish a new
origin for it. No model DLL, weights, external checkout or code execution is used.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DECLARATIONS = ROOT / 'tools/model_layouts/original.json'
HEADER = ROOT / 'native_runtime/models/original/weight_layouts.h'
MODELS = ('original', 'small_fp8')
ENCODINGS = ('RawBytes', 'PackedFp8', 'InterleavedQkv', 'PackedProjection')
FIELDS = ['name', 'byte_begin', 'byte_end', 'encoding', 'rows', 'columns', 'inner_tiles']


def validate(document):
    if not isinstance(document, dict) or document.get('schema') not in (
            'phoenix-original-weight-layouts/1', 'phoenix-small-fp8-weight-layouts/1'):
        raise ValueError('Unsupported weight-layout declaration schema')
    if document.get('attribution') != 'third_party/portable_nr/PROVENANCE.md':
        raise ValueError('Model layout attribution must be retained')
    if document.get('part_fields') != FIELDS:
        raise ValueError('Unsupported weight-layout fields')
    layouts = document.get('layouts')
    if not isinstance(layouts, list) or not layouts:
        raise ValueError('Missing weight layouts')
    sizes = set()
    for layout in layouts:
        if not isinstance(layout, dict):
            raise ValueError('Layout must be a record object')
        size = layout.get('bytes')
        if type(size) is not int or not 0 < size <= 0xffffffff or size in sizes:
            raise ValueError('Invalid or duplicate record extent')
        sizes.add(size)
        parts = layout.get('parts')
        if not isinstance(parts, list) or not parts:
            raise ValueError('Missing layout parts')
        names, previous_end = set(), 0
        for part in parts:
            if not isinstance(part, list) or len(part) != len(FIELDS):
                raise ValueError('Invalid layout part fields')
            name, begin, end, encoding, rows, columns, tiles = part
            if not isinstance(name, str) or not re.fullmatch(r'[a-z][a-z0-9_]*', name) or name in names:
                raise ValueError('Invalid or duplicate layout part name')
            names.add(name)
            if any(type(value) is not int or not 0 <= value <= 0xffffffff
                   for value in (begin, end, rows, columns, tiles)):
                raise ValueError('Invalid layout integer')
            if not previous_end <= begin < end <= size:
                raise ValueError('Overlapping or out-of-range layout part')
            if encoding not in ENCODINGS:
                raise ValueError('Unsupported tensor encoding')
            if encoding == 'PackedFp8' and (not rows or not columns or not tiles or end - begin != rows * columns):
                raise ValueError('Packed FP8 shape differs from byte extent')
            previous_end = end
        if previous_end != size:
            raise ValueError('Layout does not describe the record tail')
    return layouts


def render(document):
    layouts = validate(document)
    small = document['schema'] == 'phoenix-small-fp8-weight-layouts/1'
    model = 'small_fp8' if small else 'original'
    lines = [
        '#pragma once',
        f'// Generated by tools/generate_weight_layouts.py; edit tools/model_layouts/{model}.json.',
        '// Derived layout declarations retain third_party/portable_nr/PROVENANCE.md attribution.',
        '// Byte boundaries select payload slices; rows/columns describe decoded matrices.',
        '',
    ]
    if small:
        lines += ['namespace small_fp8_layouts {']
    else:
        lines += ['enum TensorEncoding : unsigned {',
        *[f'    {encoding} = {index}' + (',' if index + 1 < len(ENCODINGS) else '')
          for index, encoding in enumerate(ENCODINGS)],
        '};', 'struct TensorPartLayout {', '    const char* name;',
        '    unsigned byte_begin, byte_end, encoding, rows, columns, inner_tiles;', '};',
    ]
    for layout in layouts:
        lines.append(f'inline constexpr TensorPartLayout layout_{layout["bytes"]}[] = {{')
        for name, begin, end, encoding, rows, columns, tiles in layout['parts']:
            lines.append(f'    {{"{name}", {begin}, {end}, {encoding}, {rows}, {columns}, {tiles}}},')
        lines.append('};')
    lines += ['template <class Visitor> void visit_layout(size_t record_bytes, Visitor visitor) {',
              '    switch (record_bytes) {']
    for layout in layouts:
        size = layout['bytes']
        lines += [f'    case {size}:', f'        for (auto part : layout_{size})',
                  '            visitor(part);', '        break;']
    lines += ['    default:', '        throw std::runtime_error("Unsupported tensor resource layout");',
              '    }', '}', '']
    if small:
        lines += ['} // namespace small_fp8_layouts', '']
    return '\n'.join(lines)


def paths(root, model):
    if model not in MODELS:
        raise ValueError('Unsupported model layout')
    return (root / f'tools/model_layouts/{model}.json',
            root / f'native_runtime/models/{model}/weight_layouts.h')


def check(root=ROOT, model='original'):
    declarations, header = paths(root, model)
    document = json.loads(declarations.read_text(encoding='utf-8-sig'))
    expected_schema = ('phoenix-original-weight-layouts/1' if model == 'original'
                       else 'phoenix-small-fp8-weight-layouts/1')
    if document.get('schema') != expected_schema:
        raise ValueError('Layout schema does not match selected model')
    expected = render(document)
    actual = header.read_text(encoding='utf-8-sig')
    if actual != expected:
        raise ValueError('Weight-layout header is stale; run python tools/generate_weight_layouts.py')
    return len(document['layouts'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail without changing a stale header')
    parser.add_argument('--model', choices=(*MODELS, 'all'), default='all')
    args = parser.parse_args()
    counts = {}
    # Render and validate all requested declarations before changing any header.
    pending = []
    for model in MODELS if args.model == 'all' else (args.model,):
        declarations, header = paths(ROOT, model)
        if args.check:
            counts[model] = check(model=model)
        else:
            document = json.loads(declarations.read_text(encoding='utf-8-sig'))
            expected_schema = ('phoenix-original-weight-layouts/1' if model == 'original'
                               else 'phoenix-small-fp8-weight-layouts/1')
            if document.get('schema') != expected_schema:
                raise ValueError('Layout schema does not match selected model')
            pending.append((header, render(document)))
            counts[model] = len(document['layouts'])
    for header, source in pending:
        header.write_text(source, encoding='utf-8', newline='\n')
    print(json.dumps(dict(passed=True, layouts=counts, checked_only=args.check)))


if __name__ == '__main__':
    main()
