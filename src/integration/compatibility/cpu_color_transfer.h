inline bool vector_half_conversion_available() noexcept {
    static const bool available=[] {
        int features[4]{};__cpuid(features,0);
        if(features[0]<7)return false;
        __cpuid(features,1);
        constexpr int required=(1<<27)|(1<<28)|(1<<29); // OSXSAVE, AVX, F16C.
        if((features[2]&required)!=required || (_xgetbv(0)&6)!=6)return false;
        __cpuidex(features,7,0);return (features[1]&(1<<5))!=0; // AVX2.
    }();
    return available;
}

// Keep AVX instructions in a dispatched function. Ordinary builds retain their
// original CPU baseline; unsupported CPUs use the exact scalar lookup below.
__declspec(noinline) inline size_t vector_rgba8_to_half(const uint8_t* rgba,uint16_t* half,size_t count) {
    const auto scale=_mm256_set1_ps(1.f/255.f);
    size_t i=0;
    for(;i+8<=count;i+=8) {
        const auto bytes=_mm_loadl_epi64(reinterpret_cast<const __m128i*>(rgba+i));
        const auto integers=_mm256_cvtepu8_epi32(bytes);
        const auto normalized=_mm256_mul_ps(_mm256_cvtepi32_ps(integers),scale);
        const auto packed=_mm256_cvtps_ph(normalized,_MM_FROUND_TO_NEAREST_INT|_MM_FROUND_NO_EXC);
        _mm_storeu_si128(reinterpret_cast<__m128i*>(half+i),packed);
    }
    _mm256_zeroupper();return i;
}
__declspec(noinline) inline size_t vector_half_to_rgba8(const uint16_t* half,const uint8_t* input,uint8_t* output,size_t pixels) {
    const auto exponent=_mm_set1_epi16(0x7c00);
    const auto rgb_half_mask=_mm_set_epi16(0,-1,-1,-1,0,-1,-1,-1);
    const auto zero=_mm256_setzero_ps(),one=_mm256_set1_ps(1.f);
    size_t pixel=0;
    for(;pixel+2<=pixels;pixel+=2) {
        const auto raw=_mm_loadu_si128(reinterpret_cast<const __m128i*>(half+pixel*4));
        const auto invalid=_mm_cmpeq_epi16(_mm_and_si128(raw,exponent),exponent);
        if((_mm_movemask_epi8(invalid)&0x3f3f)!=0)
            throw std::runtime_error("Native bridge returned nonfinite pixels");
        // Alpha is not a color validity guide. Mask it before conversion so an
        // ignored signaling NaN cannot raise a floating-point exception.
        const auto decoded=_mm256_cvtph_ps(_mm_and_si128(raw,rgb_half_mask));
        const auto scaled=_mm256_mul_ps(_mm256_min_ps(one,_mm256_max_ps(zero,decoded)),_mm256_set1_ps(255.f));
        const auto integral=_mm256_cvttps_epi32(scaled);
        const auto fraction=_mm256_sub_ps(scaled,_mm256_cvtepi32_ps(integral));
        const auto increment=_mm256_castps_si256(_mm256_cmp_ps(fraction,_mm256_set1_ps(.5f),_CMP_GE_OQ));
        const auto rounded=_mm256_sub_epi32(integral,increment);
        const auto words=_mm_packs_epi32(_mm256_castsi256_si128(rounded),_mm256_extracti128_si256(rounded,1));
        const auto bytes=_mm_packus_epi16(words,_mm_setzero_si128());
        const auto alpha=_mm_and_si128(_mm_loadl_epi64(reinterpret_cast<const __m128i*>(input+pixel*4)),_mm_set1_epi32(int(0xff000000u)));
        _mm_storel_epi64(reinterpret_cast<__m128i*>(output+pixel*4),_mm_or_si128(bytes,alpha));
    }
    _mm256_zeroupper();return pixel;
}
