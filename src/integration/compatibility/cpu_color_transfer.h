// The WOW64 bridge moves SDR RGBA8 through RGBA16F. These are small immutable
// CPU tables, not models. Their entries are generated by the existing DirectX
// conversion, preserving its rounding and signed-zero/subnormal behavior.
inline const std::array<uint16_t, 256>& byte_half_table() {
    static const auto table = [] {
        std::array<uint16_t, 256> result{};
        for (size_t i = 0; i < result.size(); ++i)
            result[i] = DirectX::PackedVector::XMConvertFloatToHalf(float(i) / 255.f);
        return result;
    }();
    return table;
}

inline const std::array<float, 65536>& half_float_table() {
    struct Table {
        std::array<float, 65536> values;
        Table() {
            for (size_t i = 0; i < values.size(); ++i)
                values[i] = DirectX::PackedVector::XMConvertHalfToFloat(uint16_t(i));
        }
    };
    static const Table table;
    return table.values;
}

inline bool finite(float value) noexcept {
    static_assert(sizeof(float) == sizeof(uint32_t) && std::numeric_limits<float>::is_iec559);
    // Avoid the per-channel CRT classification call in 32-bit builds. This is
    // the IEEE754 exponent test; both infinities and every NaN are rejected.
    return (std::bit_cast<uint32_t>(value) & 0x7f800000u) != 0x7f800000u;
}

inline void rgba8_to_half(const std::vector<uint8_t>& rgba, std::vector<uint16_t>& half) {
    if (rgba.empty() || rgba.size() % 4 || half.size() != rgba.size())
        throw std::runtime_error("Invalid RGBA8/half conversion extent");
    const auto& table = byte_half_table();
    size_t first=0;
#if defined(_MSC_VER) && (defined(_M_IX86) || defined(_M_X64))
    if(vector_half_conversion_available())first=vector_rgba8_to_half(rgba.data(),half.data(),rgba.size());
#endif
    for (size_t i = first; i < rgba.size(); ++i) half[i] = table[rgba[i]];
}

inline void half_rgba_to_rgb(const std::vector<uint16_t>& rgba, std::vector<float>& rgb) {
    if (rgba.empty() || rgba.size() % 4 || rgb.size() != rgba.size() / 4 * 3)
        throw std::runtime_error("Invalid half/RGB conversion extent");
    const auto& table = half_float_table();
    for (size_t pixel = 0; pixel < rgba.size() / 4; ++pixel) {
        for (unsigned channel = 0; channel < 3; ++channel) {
            const auto value = rgba[pixel * 4 + channel];
            if ((value & 0x7c00u) == 0x7c00u)
                throw std::runtime_error("Native bridge returned nonfinite pixels");
            rgb[pixel * 3 + channel] = table[value];
        }
    }
}

inline uint8_t unorm8(float value) {
    if (!finite(value)) throw std::runtime_error("Nonfinite portable output");
    const float clamped = value < 0 ? 0.f : value > 1 ? 1.f : value;
    const float scaled = clamped * 255.f;
    // Match lround(float_product) exactly, including values immediately below
    // a half-integer. Adding0.5f instead would round some of those up early.
    return uint8_t(int(double(scaled) + 0.5));
}

inline void half_rgba_to_rgba8(const std::vector<uint16_t>& half,
                               const std::vector<uint8_t>& input,
                               std::vector<uint8_t>& output) {
    if (half.empty() || half.size() % 4 || input.size() != half.size())
        throw std::runtime_error("Invalid packed half/RGBA8 conversion extent");
    struct Table {
        std::array<uint8_t, 65536> values{};
        Table() {
            const auto& decoded = half_float_table();
            for (size_t i = 0; i < values.size(); ++i)
                if ((i & 0x7c00u) != 0x7c00u) values[i] = unorm8(decoded[i]);
        }
    };
    static const Table table;
    output.resize(input.size());
    size_t first=0;
#if defined(_MSC_VER) && (defined(_M_IX86) || defined(_M_X64))
    if(vector_half_conversion_available())
        first=vector_half_to_rgba8(half.data(),input.data(),output.data(),half.size()/4);
#endif
    // Full-view SDR needs no intermediate RGB32F image. Preserve exactly the
    // old half->float->UNORM8 result and the current input's alpha channel.
    for (size_t pixel = first; pixel < half.size() / 4; ++pixel) {
        for (unsigned channel = 0; channel < 3; ++channel) {
            const auto h = half[pixel * 4 + channel];
            if ((h & 0x7c00u) == 0x7c00u)
                throw std::runtime_error("Native bridge returned nonfinite pixels");
            output[pixel * 4 + channel] = table.values[h];
        }
        output[pixel * 4 + 3] = input[pixel * 4 + 3];
    }
}
